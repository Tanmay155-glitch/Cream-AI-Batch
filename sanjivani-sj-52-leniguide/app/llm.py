# Main Chat Generation Interface
# ============================================================================

def generate_chat_response(
    question: str,
    task: str = "cave_qa",
    context_records: Optional[List[Dict[str, Any]]] = None,
    provider: Optional[str] = None
) -> Dict[str, Any]:
    """
    Generate a structured, grounded response to a user question using an LLM provider.
    
    Args:
        question: The user's query or instruction.
        task: Either 'cave_qa' (default) or 'tour_planner'.
        context_records: List of cave record dictionaries retrieved from search.
        provider: 'groq', 'gemini', or None (uses environment setting).
        
    Returns:
        Dict guaranteed to have keys: 'answer', 'confidence', 'follow_up'.
    """
    if not question or not str(question).strip():
        return {
            "answer": "Please ask a question about Ajanta or Ellora caves, visiting rules, or study tour planning.",
            "confidence": "low",
            "follow_up": "For example: 'Which day is Ellora closed?' or 'Make a 3-hour plan for Ellora.'"
        }

    question_clean = str(question).strip()
    target_provider = (provider or DEFAULT_PROVIDER).lower()

    # Determine prompt files
    system_prompt = load_prompt("system_prompt.txt")
    task_file = "task_tour_planner.txt" if task == "tour_planner" else "task_cave_qa.txt"
    task_template = load_prompt(task_file)

    # Format retrieved context
    formatted_context = format_context_records(context_records)
    user_prompt = task_template.replace("{context}", formatted_context).replace("{question}", question_clean)

    # Attempt LLM API call
    raw_output: Optional[str] = None
    call_error: Optional[Exception] = None

    if target_provider == "groq":
        try:
            messages = [
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": user_prompt}
            ]
            raw_output = call_groq(messages, temperature=LLM_TEMPERATURE)
        except Exception as e:
            call_error = e

    elif target_provider == "gemini":
        try:
            raw_output = call_gemini(
                prompt_text=user_prompt,
                system_instruction=system_prompt,
                temperature=LLM_TEMPERATURE
            )
        except Exception as e:
            call_error = e

    # If active provider succeeded, clean and parse the JSON
    if raw_output:
        try:
            parsed = clean_json_response(raw_output)
            # Ensure guardrail consistency: if question is Q6 footfall, ensure low confidence
            if "diwali" in question_clean.lower() and "tourist" in question_clean.lower():
                parsed["confidence"] = "low"
            return parsed
        except Exception:
            pass

    # Safe deterministic offline fallback if provider was unconfigured, offline, or errored
    fallback = offline_fallback_response(
        question=question_clean,
        task=task,
        context_records=context_records
    )
    return fallback


