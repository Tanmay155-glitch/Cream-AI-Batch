def call_groq(messages: List[Dict[str, str]], temperature: float = 0.2) -> str:
    """
    Call Groq OpenAI-compatible Chat Completions REST API.
    Endpoint: https://api.groq.com/openai/v1/chat/completions
    """
    api_key = os.getenv("GROQ_API_KEY", GROQ_API_KEY)
    if not api_key or api_key.startswith("your_"):
        raise ValueError("GROQ_API_KEY is not configured in environment or .env.")

    model = os.getenv("GROQ_MODEL", GROQ_MODEL)
    url = "https://api.groq.com/openai/v1/chat/completions"
    headers = {
        "Authorization": f"Bearer {api_key}",
        "Content-Type": "application/json"
    }
    payload = {
        "model": model,
        "messages": messages,
        "temperature": temperature,
        "response_format": {"type": "json_object"}
    }

    response = requests.post(url, headers=headers, json=payload, timeout=LLM_TIMEOUT)
    response.raise_for_status()
    result = response.json()
    return result["choices"][0]["message"]["content"]


def call_gemini(prompt_text: str, system_instruction: str = "", temperature: float = 0.2) -> str:
    """
    Call Google Gemini REST API (v1beta).
    Endpoint: https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent
    """
    api_key = os.getenv("GEMINI_API_KEY", GEMINI_API_KEY)
    if not api_key or api_key.startswith("your_"):
        raise ValueError("GEMINI_API_KEY is not configured in environment or .env.")

    model = os.getenv("GEMINI_MODEL", GEMINI_MODEL)
    url = f"https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent?key={api_key}"
    headers = {"Content-Type": "application/json"}

    contents = [{"parts": [{"text": prompt_text}]}]
    payload: Dict[str, Any] = {
        "contents": contents,
        "generationConfig": {
            "temperature": temperature,
            "responseMimeType": "application/json"
        }
    }
    if system_instruction:
        payload["systemInstruction"] = {
            "parts": [{"text": system_instruction}]
        }

    response = requests.post(url, headers=headers, json=payload, timeout=LLM_TIMEOUT)
    response.raise_for_status()
    result = response.json()
    return result["candidates"][0]["content"]["parts"][0]["text"]


