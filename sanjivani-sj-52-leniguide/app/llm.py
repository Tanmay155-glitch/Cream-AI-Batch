def load_prompt(filename: str) -> str:
    """
    Load a prompt template from the prompts/ directory.
    Falls back to embedded defaults if file is missing.
    """
    file_path = PROMPTS_DIR / filename
    if file_path.exists():
        try:
            return file_path.read_text(encoding="utf-8").strip()
        except Exception as e:
            print(f"⚠ Warning: Could not read prompt file {filename}: {e}")

    # Built-in fallbacks if files cannot be read
    if "system" in filename:
        return (
            "You are LeniGuide, an expert ASI-verified heritage guide for Ajanta & Ellora. "
            "Strict rules: Ajanta closed Mondays (9am-5pm); Ellora closed Tuesdays (sunrise-sunset); "
            "ASI fee Rs 40 cash / Rs 35 online; students under 15 FREE. "
            "For unanswerable queries like Diwali footfall, respond with 'I don't know' and confidence: low. "
            "Always output JSON with keys: answer, confidence, follow_up."
        )
    elif "tour_planner" in filename:
        return (
            "=== TASK: TOUR PLANNER ===\nContext:\n{context}\n\nRequest:\n{question}\n\n"
            "Build an itinerary enforcing Monday/Tuesday closures, ticket math (under 15 free), "
            "and time allocations. Output JSON with answer, confidence, follow_up."
        )
    else:
        return (
            "=== TASK: CAVE QA ===\nContext:\n{context}\n\nQuestion:\n{question}\n\n"
            "Answer factually using ASI context. For out-of-scope stats, state 'I don't know'. "
            "Output JSON with answer, confidence, follow_up."
        )


def format_context_records(records: Optional[List[Dict[str, Any]]]) -> str:
    """Format a list of cave records into a clean text block for prompt injection."""
    if not records:
        return "No specific cave records retrieved. Use general verified ASI monument knowledge."

    formatted_lines = []
    for idx, r in enumerate(records, 1):
        site = r.get("site", "Monument")
        cave_no = r.get("cave_no", "N/A")
        period = r.get("religion_period", "Ancient")
        highlights = r.get("highlights", "")
        visit_info = r.get("visit_info", "")
        score = r.get("score")
        score_str = f" [Similarity: {score}]" if score is not None else ""
        
        entry = (
            f"[{idx}] {site} Cave {cave_no}{score_str}\n"
            f"    - Religion & Period: {period}\n"
            f"    - Architectural Highlights: {highlights}\n"
            f"    - Visit & Timing Info: {visit_info}"
        )
        formatted_lines.append(entry)

    return "\n\n".join(formatted_lines)


