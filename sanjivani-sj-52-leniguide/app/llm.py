def clean_json_response(raw_text: str) -> Dict[str, Any]:
    """
    Extract and validate structured JSON from raw LLM output.
    Guarantees keys: 'answer', 'confidence', 'follow_up'.
    """
    if not raw_text or not raw_text.strip():
        return {
            "answer": "No response was generated by the language model.",
            "confidence": "low",
            "follow_up": "Would you like to rephrase your question?"
        }

    text = raw_text.strip()

    # Strip markdown code blocks if present (```json ... ``` or ``` ... ```)
    if text.startswith("```"):
        text = re.sub(r"^```[a-zA-Z]*\s*", "", text)
        text = re.sub(r"\s*```$", "", text)
        text = text.strip()

    # Attempt direct json.loads
    try:
        data = json.loads(text)
        if isinstance(data, dict):
            return _normalize_response_dict(data)
    except json.JSONDecodeError:
        pass

    # Find the outermost balanced curly braces
    match = re.search(r"(\{.*\})", text, re.DOTALL)
    if match:
        try:
            data = json.loads(match.group(1))
            if isinstance(data, dict):
                return _normalize_response_dict(data)
        except json.JSONDecodeError:
            pass

    # If parsing failed completely, package the text safely into the expected schema
    return {
        "answer": text,
        "confidence": "medium",
        "follow_up": "Would you like more details or an itinerary breakdown for these caves?"
    }


def _normalize_response_dict(data: Dict[str, Any]) -> Dict[str, Any]:
    """Ensure exact keys and proper types in response dictionary."""
    answer = data.get("answer") or data.get("response") or data.get("text") or "Information retrieved."
    confidence = data.get("confidence", "high")
    follow_up = data.get("follow_up") or data.get("followup") or data.get("suggestion") or "Can I help plan your visit?"

    # Normalize confidence to lowercase string
    if isinstance(confidence, (int, float)):
        if confidence >= 0.8:
            confidence = "high"
        elif confidence >= 0.5:
            confidence = "medium"
        else:
            confidence = "low"
    else:
        confidence = str(confidence).lower().strip()
        if confidence not in ["high", "medium", "low"]:
            confidence = "medium"

    return {
        "answer": str(answer).strip(),
        "confidence": confidence,
        "follow_up": str(follow_up).strip()
    }


