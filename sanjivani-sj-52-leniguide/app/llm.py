    """
    OOP Client wrapper for LeniGuide LLM operations.
    Enables instantiation: client = LLMClient(provider="groq")
    """

    def __init__(self, provider: Optional[str] = None, temperature: float = 0.2):
        self.provider = (provider or DEFAULT_PROVIDER).lower()
